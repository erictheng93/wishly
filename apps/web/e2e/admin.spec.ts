import { expect, test } from '@playwright/test'
import { loginBrowser, makeStaff, registerUser, sql, skipOtpCooldown, waitForOtp } from './helpers'

test('後台：統計、使用者操作、復原信、稽核與旗標', async ({ browser }) => {
  const staff = await registerUser({ tag: 'admin' })
  const user = await registerUser({ name: `後台測試${Date.now()}` })
  makeStaff(staff.email)
  const id = (await (await user.api.get('me')).json()).id as string
  const ctx = await browser.newContext()
  await loginBrowser(ctx, staff)
  const page = await ctx.newPage()
  try {
    await page.goto('/admin')
    const stats = await (await staff.api.get('admin/stats')).json()
    await expect(page.getByTestId('stat-users')).toHaveText(String(stats.users))
    await page.getByRole('button', { name: '使用者', exact: true }).click()
    await page.getByLabel('搜尋使用者').fill(user.name)
    await page.getByRole('button', { name: '搜尋', exact: true }).click()
    const row = page.getByRole('article').filter({ hasText: user.name })
    await expect(row).toBeVisible()
    async function act(name: string) {
      await row.getByRole('button', { name, exact: true }).click()
      const dlg = page.getByRole('dialog')
      await expect(dlg.getByRole('button', { name: '確認執行' })).toBeDisabled()
      await dlg.getByLabel('操作原因').fill('E2E 使用者協助')
      await dlg.getByRole('button', { name: '確認執行' }).click()
      await expect(dlg).not.toBeVisible()
    }
    await act('停權')
    await expect(row.getByText('已封鎖')).toBeVisible()
    expect((await user.api.get('me')).status()).toBe(403)
    await act('解除停權')
    await expect(row.getByText('已封鎖')).toHaveCount(0)
    await act('設為 staff')
    await expect(row.getByRole('button', { name: '取消 staff', exact: true })).toBeVisible()
    await act('取消 staff')
    sql(`INSERT INTO auth_identities(user_id,provider,provider_uid) VALUES ('${id}','line','e2e-${id}')`)
    await page.getByRole('button', { name: '搜尋', exact: true }).click()
    await act('解除 LINE 綁定')
    await expect(row.getByRole('button', { name: '解除 LINE 綁定' })).toHaveCount(0)
    skipOtpCooldown(user.email)
    await act('寄送復原驗證信')
    expect(await waitForOtp(user.email, /重設密碼/)).toMatch(/^\d{6}$/)
    await page.getByRole('link', { name: '稽核紀錄', exact: true }).click()
    await page.getByLabel('對象 UUID').fill(id)
    await page.getByRole('button', { name: '查詢', exact: true }).click()
    await expect(page.getByRole('article').filter({ hasText: 'user.recovery' })).toBeVisible()
    await page.screenshot({ path: 'test-results/admin-audit-desktop.png', fullPage: true })
    await page.goto('/admin')
    await page.getByRole('button', { name: '系統旗標', exact: true }).click()
    await page.getByRole('checkbox').click()
    await page.getByRole('dialog').getByRole('button', { name: '確認', exact: true }).click()
    await expect.poll(async () => (await (await staff.api.get('admin/system-flags')).json()).data.find((f: any) => f.key === 'read_only').value).toBe(true)
    await page.getByRole('checkbox').click()
    await page.getByRole('dialog').getByRole('button', { name: '確認', exact: true }).click()
    await expect.poll(async () => (await (await staff.api.get('admin/system-flags')).json()).data.find((f: any) => f.key === 'read_only').value).toBe(false)
    await page.getByRole('button', { name: '使用者', exact: true }).click()
    await page.getByLabel('搜尋使用者').fill(user.name)
    await page.getByRole('button', { name: '搜尋', exact: true }).click()
    await expect(row).toBeVisible()
    await expect(page.getByRole('button', { name: '搜尋', exact: true })).toBeEnabled()
    await page.screenshot({ path: 'test-results/admin-users-desktop.png', fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: 'test-results/admin-users-mobile.png', fullPage: true })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  } finally {
    await staff.api.put('admin/system-flags/read_only', { data: { value: false } })
    await Promise.all([ctx.close(), staff.api.dispose(), user.api.dispose()])
  }
})

test('後台篩選與分頁：LINE 使用者、清單、錢包與履約類型', async ({ browser }) => {
  const staff = await registerUser({ tag: 'filters' })
  makeStaff(staff.email)
  const tag = `filter_${Date.now()}`
  sql(`INSERT INTO users(display_name,blocked_at) SELECT '${tag}_' || n, CASE WHEN n=1 THEN now() END FROM generate_series(1,22) n;
    INSERT INTO auth_identities(user_id,provider,provider_uid) SELECT id,'line',id::text FROM users WHERE display_name LIKE '${tag}%';
    INSERT INTO point_wallets(user_id,status) SELECT id,'frozen' FROM users WHERE display_name='${tag}_1';
    INSERT INTO wishlists(owner_id,type,status,slug,title,moderation_status,moderation_reason) SELECT id,'registry','active',left(md5(id::text),10),'${tag}', 'hidden','E2E moderation' FROM users WHERE display_name LIKE '${tag}%';`)
  const ctx = await browser.newContext()
  await loginBrowser(ctx, staff)
  const page = await ctx.newPage()
  try {
    await page.goto('/admin')
    await page.getByRole('button', { name: '使用者', exact: true }).click()
    await page.getByLabel('搜尋使用者').fill(tag)
    await page.getByLabel('登入來源').selectOption('line')
    await page.getByRole('button', { name: '搜尋', exact: true }).click()
    await expect(page.getByRole('article')).toHaveCount(20)
    await page.getByRole('button', { name: '載入更多使用者' }).click()
    await expect(page.getByRole('article')).toHaveCount(22)
    await page.getByLabel('帳號狀態').selectOption('blocked')
    await expect(page.getByRole('button', { name: '載入更多使用者' })).toHaveCount(0)
    await page.getByRole('button', { name: '搜尋', exact: true }).click()
    await expect(page.getByRole('article')).toHaveCount(1)
    await expect(page.getByRole('article')).toContainText('已封鎖')
    await expect(page.getByRole('button', { name: '解除 LINE 綁定' })).toBeDisabled()
    await expect(page.getByRole('button', { name: '寄送復原驗證信' })).toBeDisabled()
    await page.getByRole('button', { name: '清單搜尋', exact: true }).click()
    await page.getByLabel('清單狀態').selectOption('active')
    await page.getByLabel('下架狀態').selectOption('hidden')
    await page.getByRole('button', { name: '搜尋', exact: true }).click()
    await expect(page.getByRole('article')).toHaveCount(20)
    await page.getByRole('button', { name: '載入更多清單' }).click()
    await expect(page.getByRole('article')).toHaveCount(22)
    await page.getByRole('link', { name: '點數錢包', exact: true }).click()
    await expect(page.getByRole('button', { name: '搜尋', exact: true })).toBeEnabled()
    await page.getByLabel('搜尋使用者').fill(tag)
    await page.getByLabel('錢包狀態').selectOption('frozen')
    await page.getByRole('button', { name: '搜尋', exact: true }).click()
    await expect(page.getByRole('article')).toHaveCount(1)
    await expect(page.getByRole('article')).toContainText('已凍結')
    await page.getByLabel('錢包狀態').selectOption('none')
    await page.getByRole('button', { name: '搜尋', exact: true }).click()
    await expect(page.getByRole('article')).toHaveCount(20)
    await page.getByRole('button', { name: '載入更多錢包' }).click()
    await expect(page.getByRole('article')).toHaveCount(21)
    await page.goto('/admin/orders')
    const response = page.waitForResponse(r => r.url().includes('/admin/orders?') && r.url().includes('fulfillment_type=catalog'))
    await page.getByLabel('履約類型').selectOption('catalog')
    expect((await response).status()).toBe(200)
  } finally { await Promise.all([ctx.close(), staff.api.dispose()]) }
})
